import { type AnySQLiteColumn, index, integer, sqliteTable, text, uniqueIndex } from "drizzle-orm/sqlite-core";
import { FILE_LIFECYCLE_STATUSES, FILE_VISIBILITIES, SCAN_STATUSES, UPLOAD_SESSION_STATUSES } from "@/lib/constants";
import { createdAt, id, timestamp, updatedAt } from "./_shared";
import { departments, memberships, organizations } from "./organizations";

/**
 * Invariants the database cannot express and services must enforce transactionally:
 * - parent folder shares the organization of the child and respects department boundaries
 * - folder cycles are rejected before a move
 */
export const folders = sqliteTable(
  "folders",
  {
    id: id(),
    organizationId: text("organization_id")
      .notNull()
      .references(() => organizations.id, { onDelete: "cascade" }),
    departmentId: text("department_id").references(() => departments.id, { onDelete: "set null" }),
    parentFolderId: text("parent_folder_id").references((): AnySQLiteColumn => folders.id, { onDelete: "restrict" }),
    name: text("name").notNull(),
    createdByMembershipId: text("created_by_membership_id")
      .notNull()
      .references(() => memberships.id, { onDelete: "restrict" }),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
    deletedAt: timestamp("deleted_at"),
  },
  (t) => [
    index("folders_org_parent_idx").on(t.organizationId, t.parentFolderId),
    index("folders_org_department_idx").on(t.organizationId, t.departmentId),
  ],
);

/**
 * current_version_id intentionally has no database foreign key: files and file_versions
 * reference each other, and SQLite cannot create both constraints without deferred DDL.
 * Services set it inside the same transaction that makes a version available and
 * verify it belongs to the file.
 */
export const files = sqliteTable(
  "files",
  {
    id: id(),
    organizationId: text("organization_id")
      .notNull()
      .references(() => organizations.id, { onDelete: "cascade" }),
    departmentId: text("department_id").references(() => departments.id, { onDelete: "set null" }),
    folderId: text("folder_id").references(() => folders.id, { onDelete: "restrict" }),
    ownerMembershipId: text("owner_membership_id")
      .notNull()
      .references(() => memberships.id, { onDelete: "restrict" }),
    displayName: text("display_name").notNull(),
    description: text("description"),
    currentVersionId: text("current_version_id"),
    visibility: text("visibility", { enum: FILE_VISIBILITIES }).notNull().default("private"),
    lifecycleStatus: text("lifecycle_status", { enum: FILE_LIFECYCLE_STATUSES }).notNull().default("pending"),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
    deletedAt: timestamp("deleted_at"),
  },
  (t) => [
    index("files_org_status_idx").on(t.organizationId, t.lifecycleStatus),
    index("files_org_folder_idx").on(t.organizationId, t.folderId),
    index("files_org_department_idx").on(t.organizationId, t.departmentId),
    index("files_org_owner_idx").on(t.organizationId, t.ownerMembershipId),
    index("files_org_name_idx").on(t.organizationId, t.displayName),
    index("files_org_created_idx").on(t.organizationId, t.createdAt),
  ],
);

export const fileVersions = sqliteTable(
  "file_versions",
  {
    id: id(),
    fileId: text("file_id")
      .notNull()
      .references(() => files.id, { onDelete: "cascade" }),
    versionNumber: integer("version_number").notNull(),
    /** Generated by the server. Never derived from the untrusted filename. */
    objectKey: text("object_key").notNull(),
    originalFilename: text("original_filename").notNull(),
    detectedContentType: text("detected_content_type"),
    declaredContentType: text("declared_content_type").notNull(),
    sizeBytes: integer("size_bytes").notNull(),
    checksum: text("checksum"),
    uploadedByMembershipId: text("uploaded_by_membership_id")
      .notNull()
      .references(() => memberships.id, { onDelete: "restrict" }),
    scanStatus: text("scan_status", { enum: SCAN_STATUSES }).notNull().default("pending"),
    createdAt: createdAt(),
  },
  (t) => [
    uniqueIndex("file_versions_file_number_unique").on(t.fileId, t.versionNumber),
    uniqueIndex("file_versions_object_key_unique").on(t.objectKey),
  ],
);

export const tags = sqliteTable(
  "tags",
  {
    id: id(),
    organizationId: text("organization_id")
      .notNull()
      .references(() => organizations.id, { onDelete: "cascade" }),
    name: text("name").notNull(),
  },
  (t) => [uniqueIndex("tags_org_name_unique").on(t.organizationId, t.name)],
);

export const fileTags = sqliteTable(
  "file_tags",
  {
    fileId: text("file_id")
      .notNull()
      .references(() => files.id, { onDelete: "cascade" }),
    tagId: text("tag_id")
      .notNull()
      .references(() => tags.id, { onDelete: "cascade" }),
  },
  (t) => [uniqueIndex("file_tags_unique").on(t.fileId, t.tagId), index("file_tags_tag_idx").on(t.tagId)],
);

export const uploadSessions = sqliteTable(
  "upload_sessions",
  {
    id: id(),
    organizationId: text("organization_id")
      .notNull()
      .references(() => organizations.id, { onDelete: "cascade" }),
    fileId: text("file_id").references(() => files.id, { onDelete: "cascade" }),
    versionId: text("version_id").references(() => fileVersions.id, { onDelete: "cascade" }),
    objectKey: text("object_key").notNull(),
    expectedSizeBytes: integer("expected_size_bytes").notNull(),
    declaredContentType: text("declared_content_type").notNull(),
    status: text("status", { enum: UPLOAD_SESSION_STATUSES }).notNull().default("pending"),
    expiresAt: timestamp("expires_at").notNull(),
    createdByMembershipId: text("created_by_membership_id")
      .notNull()
      .references(() => memberships.id, { onDelete: "restrict" }),
    createdAt: createdAt(),
  },
  (t) => [
    uniqueIndex("upload_sessions_object_key_unique").on(t.objectKey),
    index("upload_sessions_status_expires_idx").on(t.status, t.expiresAt),
    index("upload_sessions_org_idx").on(t.organizationId),
  ],
);
